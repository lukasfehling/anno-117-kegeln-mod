# Part 3 of the mod build: Trichter in the delivery contracts offered at NPC lighthouses (traders, pirates, rivals).
#
#   python build_contracts.py <mod-dir>
#
# The game fills each lighthouse's contract book from the provider's "Contract Delivery Pool" (AssetPool with
# weighted goods, referenced by ContractProvider/DeliveryGoods). Amount and reward of a contract are computed by
# the game from the good's price. We only add Trichter with a weight of roughly 13 % of each pool, so a Trichter
# contract shows up regularly but not permanently.
import sys, os
import xml.dom.minidom

OUT = sys.argv[1]
TRICHTER = 2001000300
SHARE = 0.13
# pool GUID: (provider, weight sum of the vanilla pool)
POOLS = {
    37360: ('Diana (Latium trader)', 37), 37363: ('Procurator (Albion trader)', 36), 37362: ('Manx (Albion trader)', 33),
    37364: ('Caeso (Latium pirate)', 12), 37367: ('Voada (Albion pirate)', 26), 159289: ('Kandis (Aegyptus pirate)', 101),
    37342: ('Dorian (rival)', 25), 37356: ('Tarragon (rival)', 33), 37365: ('Licia Ma (rival)', 39), 37366: ('Athr (rival)', 35),
    37357: ('Zara (rival)', 27), 37358: ('Concordia (rival)', 23), 37359: ('Neferneru (rival)', 35),
    # default pool, presumably used by providers without their own pool (Valeria, Heron, Valeria in Aegyptus)
    32742: ('default delivery pool', 26),
}

x = '<ModOps>\n  <!-- Kegel-Quest: Trichter delivery contracts at NPC lighthouses. Generated by build_contracts.py. -->\n'
for pool, (who, total) in POOLS.items():
    w = max(1, round(total * SHARE / (1 - SHARE)))
    x += f'''  <ModOp GUID="{pool}" Add="AssetPool/AssetList"> <!-- {who}: weight {w} of {total + w} -->
    <Item>
      <Probability>{w}</Probability>
      <Asset>{TRICHTER}</Asset>
    </Item>
  </ModOp>
'''
x += '</ModOps>\n'
dst = os.path.join(OUT, 'data/base/config/export/contracts.include.xml')
open(dst, 'w', encoding='utf-8', newline='\n').write(x)
xml.dom.minidom.parse(dst)
print('contract pools extended:', len(POOLS))
